// Helper para no repetir el desglose de precios en cada destino:
// el precio final es la suma de base + impuesto + tasas.
function breakdown(priceBeforeTax: number, tax: number, extra: number): Destination['priceBreakdown'] {
  return { priceBeforeTax, tax, extra, finalPrice: priceBeforeTax + tax + extra };
}

